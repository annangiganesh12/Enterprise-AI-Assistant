from app.langgraph.graph import graph
from langgraph.checkpoint.memory import MemorySaver
from typing import List, Tuple

# We compile the graph here for use in services/evals
# In production (main.py), you use PostgresSaver; here MemorySaver is fine for tests/evals
checkpointer = MemorySaver()
app_graph = graph.compile(checkpointer=checkpointer)

def run_chat_session(history: List[Tuple[str, str]], current_query: str) -> str:
    """
    Wrapper function to interact with the existing RAG graph orchestration.
    Matches the signature required by deepeval conversational metrics.

    Args:
        history: List of (role, message) tuples.
        current_query: The latest user message.
    Returns:
        The AI assistant's response as a string.
    """
    # LangGraph uses 'thread_id' to track conversations.
    # For evals, we use a consistent ID to maintain state across the simulation.
    config = {"configurable": {"thread_id": "eval_session_1"}}

    # Convert history to the format expected by the RAGState
    messages = []
    for role, text in history:
        messages.append((role, text))
    messages.append(("user", current_query))

    inputs = {
        "messages": messages,
        "route": "general" # Default route; the router_node in the graph will determine the actual path
    }

    try:
        result = app_graph.invoke(inputs, config)
        # Return the content of the last message produced by the orchestration
        if "messages" in result and len(result["messages"]) > 0:
            return result["messages"][-1].content
        return "No response generated by the graph."
    except Exception as e:
        return f"Error occurred during graph execution: {str(e)}"

def run_single_query(query: str) -> str:
    """
    Simple wrapper for single-turn E2E evaluation.
    Takes a query string and returns the response string.
    """
    return run_chat_session([], query)
