    # Function that converts a user question into SQL query

def generate_sql(question: str) -> str:

    prompt = f"""
        You are a PostgreSQL SQL expert.

        Convert the user's question into a SQL query.

        Database schema:

        {DATABASE_SCHEMA}

        User question:
        {question}

        Rules:
         - Generate ONLY a SELECT query.
         - Do not generate INSERT, UPDATE, DELETE, DROP, ALTER, CREATE, TRUNCATE
           or any other modifying query.
         - Use only the tables and columns present in the schema.
         - Use proper JOINs when information comes from multiple tables.
         - Return ONLY the SQL query.
         - Do not use markdown code fences.

    """

    response = llm.invoke(prompt)

    content = response.content

    if isinstance(content, str):
      sql = content

    elif isinstance(content, list):
      sql = "\n".join(
        item["text"]
        for item in content
        if isinstance(item, dict)
        and item.get("type") == "text"
    )

    else:
      sql = str(content)

    sql = sql.strip()

    if sql.startswith("```"):
      sql = sql.replace("```sql", "")
      sql = sql.replace("```", "")
      sql = sql.strip()

    return sql


       # Function to validate the SQL query that is generated by LLM 

def validate_sql(sql: str) -> bool:

    normalized_sql = sql.strip().lower()

    # QUERY MUST start with SELECT, now we are checking for that
    if not normalized_sql.startswith("select"):
        return False

    # Check for aggregations (SUM, AVG, COUNT, MAX, MIN)
    # We check for these keywords followed by an open parenthesis to ensure they are functions
    aggregation_keywords = ["sum(", "avg(", "count(", "max(", "min("]
    for keyword in aggregation_keywords:
        if keyword in normalized_sql:
            raise ValueError("Aggregation detected. You MUST use analytics_tool for reports, summaries, and statistical analysis.")

    forbidden_keywords = [
        "insert ",
        "update ",
        "delete ",
        "drop ",
        "alter ",
        "create ",
        "truncate ",
        "grant ",
        "revoke ",
    ]

    for keyword in forbidden_keywords:
        if keyword in normalized_sql:
            return False

    return True

    # Execute the SQL query on the database

def execute_sql(sql: str):

    if not validate_sql(sql):
        raise ValueError("Only read-only SELCET queries are allowed.")

    db =  SessionLocal()

    try:

        result = db.execute(text(sql))

        rows = result.mappings().all()

        return [dict(row) for row in rows]
    
    finally:
        db.close()

def generate_answer(question: str, sql: str, results):

  prompt = f"""
     You are an enterprise AI assistant.

     Answer the user's question using the SQL query result.

     User question:
     {question}

     SQL query:
     {sql}

     Database result:
     {results}

     Instructions:
     - Answer using only the database result.
     - Do not invent information.
     - Give a concise, natural-language answer.

    """
  response = llm.invoke(prompt)
  content = response.content

  if isinstance(content, str):
        answer = content

  elif isinstance(content, list):
        answer = "\n".join(
            item["text"]
            for item in content
            if isinstance(item, dict)
            and item.get("type") == "text"
        )

  else:
        answer = str(content)

  return answer.strip()  
  
             # Main SQL tool

def sql_tool(question: str):

    sql = generate_sql(question)

    print("\nGenerated SQL:")
    print(sql)

    results = execute_sql(sql)

    answer = generate_answer(
        question,
        sql,
        results
    )

    return {
        "sql": sql,
        "results": results,
        "answer": answer
    }


